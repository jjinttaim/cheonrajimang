import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const base=process.env.SEARCHPROOF_TEST_URL||'http://127.0.0.1:8000';
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:2});
const page=await context.newPage();
const errors=[],requests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.url().includes('/api/'))requests.push({method:r.method(),url:r.url()});});
fs.mkdirSync('../artifacts',{recursive:true});
await page.goto(base);
await page.getByTestId('basemap-status').filter({hasText:'고해상도 벡터'}).waitFor({timeout:45000});
const retina=await page.locator('canvas').evaluate(c=>({width:c.width,css:c.clientWidth}));
assert.equal(retina.width,retina.css*2);
await page.screenshot({path:'../artifacts/map-vector-overview.png'});
await page.getByRole('button',{name:'지도만 보기',exact:true}).click();
await page.getByRole('button',{name:'골목과 건물까지 확대',exact:true}).click();
await page.waitForTimeout(1800);
await page.screenshot({path:'../artifacts/map-vector-detail.png'});
await page.locator('.map-home').click();
await page.getByRole('button',{name:'수색 레이어 켜기',exact:true}).click();
const previewResponse=page.waitForResponse(r=>r.url().includes('/forecast?')&&r.url().includes('seconds=1800'));
await page.getByRole('button',{name:'시간 미리보기',exact:true}).click();
const first=await (await previewResponse).json();
await page.getByTestId('live-speed').waitFor();
assert.equal(first.projection_seconds,1800);
assert.equal(first.speed.traffic_connected,false);
const next=page.waitForResponse(r=>r.url().includes('/forecast?')&&r.url().includes('seconds=7200'));
await page.getByLabel('기준 버전 이후 시간',{exact:true}).fill('120');
const second=await (await next).json();
await page.getByTestId('live-speed').waitFor();
assert.notDeepEqual(first.zones,second.zones);
await page.waitForTimeout(700);
await page.screenshot({path:'../artifacts/time-preview-120m.png'});
const auto=page.waitForResponse(r=>r.url().includes('/forecast?')&&!r.url().includes('seconds='));
await page.getByRole('button',{name:'실시간 추정',exact:true}).click();
const live1=await (await auto).json();
await page.getByTestId('live-speed').waitFor();
const poll=page.waitForResponse(r=>r.url().includes('/forecast?')&&!r.url().includes('seconds='),{timeout:22000});
const live2=await (await poll).json();
assert.ok(live2.projection_seconds>=live1.projection_seconds+15);
assert.equal(live2.saved,false);
await page.waitForTimeout(400);
await page.screenshot({path:'../artifacts/map-live-desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(700);
await page.screenshot({path:'../artifacts/map-live-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.getByRole('button',{name:'기준 지도',exact:true}).click();
await page.getByText('위치, 경사, 토지피복, 도로에 따라 이동을 계산합니다.',{exact:true}).waitFor();
assert.ok(requests.every(r=>r.method==='GET'));
assert.deepEqual(errors,[]);
// No external tile bulk download: simulate provider failure; local calculations still load.
const fallback=await context.newPage();
await fallback.route('https://tiles.openfreemap.org/**',route=>route.abort());
await fallback.goto(base);
await fallback.getByTestId('basemap-status').filter({hasText:'오프라인 분석 지도'}).waitFor({timeout:15000});
await fallback.getByText(/온라인 지도를 불러오지 못해/).waitFor();
assert.equal(await fallback.locator('canvas').count(),1);
console.log(JSON.stringify({retina,liveTicks:[live1.projection_seconds,live2.projection_seconds],errors,mutations:requests.filter(r=>r.method!=='GET').length,fallback:true}));
await browser.close();

